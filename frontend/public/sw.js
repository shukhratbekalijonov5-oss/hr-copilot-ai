/*
 * HR Copilot AI — service worker.
 *
 * ## This does NOT make the product offline-first
 *
 * Everything this app is for — jobs, applications, chat, AI answers, billing
 * — is server state that is wrong the moment it is stale. So the worker
 * caches the things that cannot be wrong (the build's own static assets) and
 * one offline page, and it gets out of the way of everything else.
 *
 * Its real job is installability plus an honest offline screen. A reader who
 * loses signal should be told so, not shown yesterday's shortlist as though
 * it were today's.
 *
 * ## Nothing authenticated is ever written to a cache
 *
 * `NEVER_CACHE` mirrors `lib/pwa/config.ts` and covers every API route, the
 * auth screens, settings and billing. The reasoning is not performance, it is
 * correctness on a shared device: a cached `/api/auth/me` handed to the next
 * person to open the app is an account leak, and a cached candidate list is a
 * confidentiality breach. Those responses go to the network and stay there.
 *
 * Written as a plain file rather than generated by a plugin: the whole thing
 * is 80 lines, and a build-time PWA plugin would take over caching decisions
 * that are exactly the ones this product must make deliberately.
 */

const VERSION = "hrc-v1";
const STATIC_CACHE = `${VERSION}-static`;
const OFFLINE_URL = "/offline";

/** Kept in step with `NEVER_CACHE_PREFIXES` in lib/pwa/config.ts. */
const NEVER_CACHE = ["/api/", "/auth/", "/login", "/register", "/settings", "/plans"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(STATIC_CACHE)
      .then((cache) => cache.addAll([OFFLINE_URL]))
      // `skipWaiting` so a fixed worker reaches readers on their next
      // navigation rather than whenever they happen to close every tab.
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith("hrc-") && !key.startsWith(VERSION))
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

function isNeverCached(url) {
  return NEVER_CACHE.some((prefix) => url.pathname.startsWith(prefix));
}

self.addEventListener("fetch", (event) => {
  const { request } = event;

  // Only GET. A POST is an action, and replaying one from a cache would
  // repeat it — applying to a job twice, or starting a second checkout.
  if (request.method !== "GET") return;

  const url = new URL(request.url);

  // Another origin's asset is not ours to cache or reason about.
  if (url.origin !== self.location.origin) return;

  /*
   * Authenticated and sensitive routes: straight to the network, never
   * stored, and never served from a cache. If the network is down the
   * browser's own failure is the honest answer for an API call.
   */
  if (isNeverCached(url)) return;

  /*
   * Navigations are network-first: a page is only useful if it is current.
   * The offline page is the fallback, so losing signal produces a real
   * screen instead of the browser's dinosaur.
   */
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        caches.match(OFFLINE_URL).then((cached) => cached ?? Response.error()),
      ),
    );
    return;
  }

  /*
   * Build assets only. `/_next/static` and `/icons` are content-addressed or
   * versioned, so a cache hit cannot be stale — which is what makes
   * cache-first safe here and nowhere else in this app.
   */
  const isStatic =
    url.pathname.startsWith("/_next/static/") || url.pathname.startsWith("/icons/");
  if (!isStatic) return;

  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ??
        fetch(request).then((response) => {
          // Only a clean same-origin 200 is worth keeping; an opaque or
          // partial response cached here would be served forever.
          if (response.ok && response.status === 200) {
            const copy = response.clone();
            void caches.open(STATIC_CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
